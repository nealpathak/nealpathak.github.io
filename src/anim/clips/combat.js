// Combat clips.
//
// Rig reminder: characters face +Z, +X is the character's LEFT, negative X
// rotation swings a limb forward, +Z rotation on an arm sweeps it toward +X
// (across the body, for the right arm).
//
// The sword extends the forearm, so the blade points wherever the forearm does.
// Two numbers do most of the work in every attack below:
//   upperArmR X = -90  -> arm horizontal, straight forward, blade extended
//   upperArmR Z        -> sweeps that forward arm right (-) to left (+)
// A horizontal slash is therefore X held near -85 while Z travels -70 to +50,
// with the elbow (forearmR X) unfolding from about -110 to -15 as it lands.
// Get that elbow wrong and the swing becomes a windmill above the head, which
// is exactly what the first pass did.
//
// Every attack is authored in three beats: an anticipation that reads at a
// glance, a strike that is over quickly, and a recovery long enough that being
// greedy costs you. The `hitStart`/`hitEnd` events bracket the frames where the
// weapon's swept hitbox is live, and `combo` marks the earliest frame the next
// attack can be buffered into.

